/**
 * Decode the `data:` fonts of `ui/fonts-src/fonts.css` into hashed `.woff2` files (R27).
 * The CSP is `default-src 'self'`, so a `data:` font would be blocked.
 *
 * `ui/fonts-src/` is a copy of the repo-root `scripts/roadmap_assets/` fonts and OFL licences. It lives in
 * `cli/` because the npm package is built in the mirror, which has no `scripts/roadmap_assets/`.
 * test/ui/fonts.test.ts fails when the copy and the source differ.
 *
 * Writes `<publicDir>/fonts/*.woff2`, the two OFL licences and the Lucide licence beside them, and `<cssOut>`: the same
 * `@font-face` rules with `url(/fonts/<name>)`. Vite copies `public/` to `dist/ui/` and bundles the CSS.
 *
 * Usage: node scripts/build-ui-fonts.mjs [--src <fonts.css>] [--public <dir>] [--css <file>]
 */
import { createHash } from 'node:crypto';
import { copyFileSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const cliRoot = path.resolve(here, '..');
export const DEFAULT_ASSETS = path.resolve(cliRoot, 'ui', 'fonts-src');

const FACE_RE = /@font-face\{([^}]*)\}/g;
const DATA_RE = /url\(data:font\/woff2;base64,([A-Za-z0-9+/=]+)\)/;

const slug = (family) => (family.startsWith('Atkinson') ? 'atkinson' : family.toLowerCase().replace(/[^a-z0-9]+/g, '-'));

/** Returns the list of written font file names. Throws when the source holds no fonts. */
export function buildFonts({ assetsDir = DEFAULT_ASSETS, publicDir, cssOut }) {
  const css = readFileSync(path.join(assetsDir, 'fonts.css'), 'utf8');
  const fontsDir = path.join(publicDir, 'fonts');
  rmSync(fontsDir, { recursive: true, force: true });
  mkdirSync(fontsDir, { recursive: true });
  const names = [];
  const rules = [];
  for (const m of css.matchAll(FACE_RE)) {
    const body = m[1];
    const data = DATA_RE.exec(body);
    const family = /font-family:"([^"]+)"/.exec(body)?.[1];
    const weight = /font-weight:(\d+)/.exec(body)?.[1];
    if (!data || !family || !weight) continue;
    const bytes = Buffer.from(data[1], 'base64');
    const hash = createHash('sha256').update(bytes).digest('hex').slice(0, 8);
    const name = `${slug(family)}-${weight}.${hash}.woff2`;
    writeFileSync(path.join(fontsDir, name), bytes);
    names.push(name);
    rules.push(body.replace(DATA_RE, `url(/fonts/${name})`));
  }
  if (names.length === 0) throw new Error(`no data: fonts found in ${path.join(assetsDir, 'fonts.css')}`);
  for (const f of ['OFL-Atkinson.txt', 'OFL-MapleMono.txt', 'LICENSE-Lucide.txt']) {
    const from = path.join(assetsDir, f);
    if (existsSync(from)) copyFileSync(from, path.join(fontsDir, f));
  }
  mkdirSync(path.dirname(cssOut), { recursive: true });
  writeFileSync(cssOut, `/* Generated by scripts/build-ui-fonts.mjs. Do not edit. */\n${rules.map((r) => `@font-face{${r}}`).join('\n')}\n`);
  return names;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const arg = (n, d) => {
    const i = process.argv.indexOf(n);
    return i > 0 ? path.resolve(process.argv[i + 1]) : d;
  };
  const names = buildFonts({
    assetsDir: arg('--src', DEFAULT_ASSETS),
    publicDir: arg('--public', path.join(cliRoot, 'ui', 'public')),
    cssOut: arg('--css', path.join(cliRoot, 'ui', 'src', 'fonts.generated.css')),
  });
  console.log(`ui fonts: ${names.length} files`);
}
